"""Local composition root: configure, authenticate, provision and serve.

Runs with uv-managed stdlib Python before project dependencies exist.
"""
from pathlib import Path
import argparse
import fcntl
import json
import os
import platform
import shutil
import socket
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'src'))
from vmforecast.settings import Settings, KEYS, read_env, config_file


class LabError(RuntimeError):
    pass


def run(argv, env=None, capture=False, timeout=300):
    """Never use a shell, and never print captured credential material."""
    try:
        result = subprocess.run([str(a) for a in argv], env=env, check=True,
                                text=True, capture_output=capture, timeout=timeout)
    except subprocess.TimeoutExpired:
        raise LabError(f'{Path(str(argv[0])).name}: operation timed out; retry the same command') from None
    except (OSError, subprocess.CalledProcessError):
        raise LabError(f'{Path(str(argv[0])).name}: command failed ({" ".join(str(a) for a in argv[1:3])}). '
                       'Check network/access and retry; existing data is preserved.') from None
    return result.stdout.strip() if capture else ''


def executable(value):
    result = shutil.which(value)
    if result is None:
        raise LabError('Executable unavailable: use configure to set its path, or install it following README')
    return result


def private_write(path, text):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    fd, temp = tempfile.mkstemp(dir=path.parent)
    try:
        with os.fdopen(fd, 'w') as f:
            os.fchmod(f.fileno(), 0o600)
            f.write(text)
        os.replace(temp, path)
    finally:
        Path(temp).unlink(missing_ok=True)


def configure(args):
    # Validate a complete candidate before replacing a participant's existing config.
    path = config_file(ROOT)
    current = read_env(path)
    if args.project is None and sys.stdin.isatty():
        args.project = input('Google Cloud project ID (Enter: synthetic experiments only): ').strip()
    from install_gcloud import target
    if args.gcloud is None and not current.get('VMFORECAST_GCLOUD_BIN'):
        installed = target(Settings.load(ROOT))
        if installed.is_file():
            args.gcloud = str(installed)
    updates = {
        'VMFORECAST_GOOGLE_CLOUD_PROJECT': args.project,
        'VMFORECAST_SOURCE_PROJECT': args.source_project,
        'VMFORECAST_STATE_DIR': args.state_dir,
        'VMFORECAST_DATA_DIR': args.data_dir,
        'VMFORECAST_RUNS_DIR': args.runs_dir,
        'VMFORECAST_GCLOUD_BIN': args.gcloud,
    }
    # Use the public dataset owner from the distributable reference configuration.
    if 'VMFORECAST_SOURCE_PROJECT' not in current:
        current.update({'VMFORECAST_SOURCE_PROJECT': read_env(ROOT/'.env.example')['VMFORECAST_SOURCE_PROJECT']})
    current.update({k: v for k, v in updates.items() if v is not None})
    validation_env = {k: v for k, v in os.environ.items() if k not in KEYS}
    validation_env.update(current)
    cfg = Settings.load(ROOT, validation_env)
    for location in (cfg.state, cfg.data, cfg.runs):
        location.mkdir(parents=True, exist_ok=True, mode=0o700)
        with tempfile.TemporaryFile(dir=location):
            pass
    private_write(path, '# Generated by sh lab configure; values are literal.\n'+
                  ''.join(k+'='+json.dumps(current[k], ensure_ascii=False)+'\n' for k in sorted(current)))
    print('Configuration saved:', path)
    print('Next: sh lab auth (Google) or sh lab bootstrap (synthetic experiments).')


def storage_check(cfg):
    for path in (cfg.state, cfg.data, cfg.runs):
        path.mkdir(parents=True, exist_ok=True, mode=0o700)
        with tempfile.TemporaryFile(dir=path):
            pass
        if shutil.disk_usage(path).free < cfg.min_free_gib*1024**3:
            raise LabError('Insufficient free disk space; choose another disk with sh lab configure')


def provision(cfg):
    if platform.system() != 'Linux' or platform.machine().lower() not in ('x86_64', 'aarch64', 'arm64'):
        raise LabError('Supported deployment: Linux x86_64/aarch64; see README for libc requirements')
    storage_check(cfg)
    uv = executable(os.environ.get('VMFORECAST_UV_BIN', 'uv'))
    env = cfg.process_env()
    # Newer uv can read the existing universal lockfile without modifying it.
    run([uv, 'sync', '--project', ROOT, '--locked', '--all-extras',
         '--no-install-project', '--no-build', '--python', sys.executable], env=env, timeout=1800)
    for key in ('JUPYTER_CONFIG_DIR', 'JUPYTER_DATA_DIR', 'JUPYTER_RUNTIME_DIR', 'IPYTHONDIR', 'MPLCONFIGDIR'):
        Path(env[key]).mkdir(parents=True, exist_ok=True, mode=0o700)
    # The default python3 kernelspec otherwise points to a bare 'python' on PATH.
    spec = Path(env['JUPYTER_DATA_DIR'])/'kernels/python3/kernel.json'
    private_write(spec, json.dumps({'argv': [str(cfg.python), '-m', 'ipykernel_launcher', '-f', '{connection_file}'],
                                  'display_name': 'VM Migration (local)', 'language': 'python'}))
    run([uv, 'pip', 'check', '--python', cfg.python], env=env)
    run([cfg.python, '-c', 'from notebook.app import JupyterNotebookApp; import ipykernel, numpy, pandas, pyarrow, matplotlib, plotly, yaml; '
         'from google.cloud import bigquery; from vmforecast import make_synthetic; '
         'assert make_synthetic(ticks=30, services=4, hosts=2, warmup=3).demand.shape == (30,4,2)'], env=env)
    return env


def cloud_fields(cfg):
    if not cfg.project or not cfg.source_project:
        raise LabError('Run sh lab configure --project YOUR_PROJECT_ID first')
    return executable(cfg.gcloud)


def authenticate(cfg):
    gcloud = cloud_fields(cfg)
    if os.environ.get('GOOGLE_APPLICATION_CREDENTIALS'):
        raise LabError('GOOGLE_APPLICATION_CREDENTIALS overrides user ADC. Unset it before sh lab auth')
    os.environ['CLOUDSDK_PYTHON'] = sys.executable
    run([gcloud, 'auth', 'login'], timeout=None)
    run([gcloud, 'projects', 'describe', cfg.project, '--format=value(projectId)'], capture=True)
    run([gcloud, 'services', 'enable', 'bigquery.googleapis.com', '--project', cfg.project, '--quiet'])
    # Sandbox: do not inherit a quota/billing project from another gcloud configuration.
    run([gcloud, 'auth', 'application-default', 'login', '--disable-quota-project'], timeout=None)
    print('ADC configured. Bootstrap will check access with a dry run.')


def cloud_check(cfg, env):
    cloud_fields(cfg)
    run([cfg.python, ROOT/'deployment/cloud_check.py'], env=env)


def port_check():
    with socket.socket() as sock:
        try:
            sock.bind(('127.0.0.1', 8888))
        except OSError:
            raise LabError('localhost:8888 is already occupied. Stop the existing server in its terminal (Ctrl+C)') from None


def serve(cfg, env):
    port_check()
    # Token auth remains enabled. stdout includes Jupyter's login URL; never persist it in source.
    print('Opening http://localhost:8888 — use Jupyter’s token URL below. Stop: Ctrl+C.', flush=True)
    argv = [str(cfg.python), '-m', 'notebook', '--no-browser',
            '--ServerApp.ip=127.0.0.1', '--ServerApp.port=8888', '--ServerApp.port_retries=0',
            '--ServerApp.root_dir='+str(ROOT),
            '--FileContentsManager.delete_to_trash=False',
            '--MappingKernelManager.cull_idle_timeout=0']
    # Foreground supervision by the terminal; no PID files or arbitrary process killing.
    child = subprocess.Popen(argv, cwd=ROOT, env=env)
    try:
        return child.wait()
    except KeyboardInterrupt:
        import signal
        child.send_signal(signal.SIGINT)
        try:
            return child.wait(timeout=15)
        except subprocess.TimeoutExpired:
            child.terminate()
            try:
                return child.wait(timeout=10)
            except subprocess.TimeoutExpired:
                child.kill()
                return child.wait()


def parser():
    p = argparse.ArgumentParser(description='Local VM Migration Forecasting deployment')
    sub = p.add_subparsers(dest='command', required=True)
    c = sub.add_parser('configure', help='Create/update private external .env without editing files')
    for name in ('project', 'source-project', 'state-dir', 'data-dir', 'runs-dir', 'gcloud'):
        c.add_argument('--'+name)
    sub.add_parser('install-gcloud', help='Install pinned standalone Google Cloud CLI outside sources')
    sub.add_parser('auth', help='Authorize CLI and ADC, enable BigQuery API')
    r = sub.add_parser('run', help='Run an arbitrary command in the managed project environment')
    r.add_argument('argv', nargs=argparse.REMAINDER)
    for name in ('bootstrap', 'prepare', 'start', 'doctor', 'test', 'verify-notebooks', 'clean-notebooks', 'audit'):
        sub.add_parser(name)
    return p


def main(argv=None):
    args = parser().parse_args(argv)
    if args.command == 'configure':
        configure(args)
        return 0
    cfg = Settings.load(ROOT)
    if args.command == 'install-gcloud':
        from install_gcloud import install
        binary = install(cfg)
        run([binary, 'version'], env={**os.environ, 'CLOUDSDK_PYTHON': sys.executable})
        values = read_env(cfg.env_file)
        values['VMFORECAST_GCLOUD_BIN'] = str(binary)
        private_write(cfg.env_file, ''.join(k+'='+json.dumps(v)+'\n' for k, v in sorted(values.items())))
        return 0
    if args.command == 'auth':
        authenticate(cfg)
        return 0
    if args.command in ('audit', 'clean-notebooks'):
        from source_hygiene import audit, clean
        (audit if args.command == 'audit' else clean)(ROOT)
        return 0
    storage_check(cfg)
    with open(cfg.state/'deployment.lock', 'a') as lock:
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            raise LabError('This checkout already has an active deployment/server command') from None
        if args.command in ('bootstrap', 'start'):
            port_check()
        env = provision(cfg)
        if args.command in ('bootstrap', 'doctor') and cfg.project:
            cloud_check(cfg, env)
        if args.command in ('bootstrap', 'start'):
            return serve(cfg, env)
        if args.command == 'run':
            argv = args.argv[1:] if args.argv[:1] == ['--'] else args.argv
            if not argv:
                raise LabError('Usage: sh lab run -- python -m vmforecast.google2019')
            env['PATH'] = str(cfg.python.parent)+os.pathsep+env.get('PATH', '')
            run(argv, env=env, timeout=None)
        elif args.command == 'test':
            run([cfg.python, '-m', 'pytest', '-q', '-p', 'no:cacheprovider', ROOT/'tests',
                 '--basetemp='+str(cfg.state/'pytest')], env=env)
        elif args.command == 'verify-notebooks':
            run([cfg.python, ROOT/'deployment/verify_notebooks.py'], env=env, timeout=1800)
        else:
            print('Environment ready; data:', cfg.data, '; runs:', cfg.runs)
    return 0


if __name__ == '__main__':
    try:
        raise SystemExit(main())
    except (LabError, ValueError, PermissionError) as error:
        print('Deployment:', error, file=sys.stderr)
        raise SystemExit(1)
    except KeyboardInterrupt:
        raise SystemExit(130)
